// npm run team — writes data/generated/team.json (TeamFile). Prints counts and store IDs only, never names.
import { mkdirSync, writeFileSync } from "node:fs";
import { loadDataset } from "../engine/data";
import { buildStoreDays } from "../engine/metrics";
import { windows } from "../engine/rows";
import { storeCompareRows, teamRows } from "../engine/team";
import type { TeamFile } from "../types";

const AS_OF = "2026-10-31";
const ds = loadDataset();
const input = { asOf: AS_OF, ...ds };
const days = buildStoreDays(ds);
const w = windows(AS_OF);

const file: TeamFile = {
  _note: "Generated by npm run team from local-data (aggregates; salesperson first name + initial only).",
  as_of: AS_OF,
  window: w.current_28d,
  baseline: w.baseline_mayjul,
  stores: storeCompareRows(input, days),
  team: teamRows(input, days),
};

const bad = JSON.stringify(file, (_k, v) => (typeof v === "number" && !Number.isFinite(v) ? (() => { throw new Error("non-finite number"); })() : v));
mkdirSync("data/generated", { recursive: true });
writeFileSync("data/generated/team.json", JSON.stringify(JSON.parse(bad), null, 1) + "\n");

const flagged = file.stores.filter((s) => s.basket_flag);
console.log(`stores: ${file.stores.length} (new: ${file.stores.filter((s) => s.is_new).map((s) => s.store_id).join(", ") || "none"})`);
console.log(`conversion below both peers: ${file.stores.filter((s) => s.conversion.vs_peers === "below").map((s) => s.store_id).join(", ") || "none"}`);
console.log(`basket_flag: ${flagged.map((s) => `${s.store_id} ₹${s.basket_flag!.rupees}`).join(", ") || "none"}`);
console.log(`team rows: ${file.team.length} (on roster: ${file.team.filter((t) => t.on_roster).length}, est_conversion set: ${file.team.filter((t) => t.est_conversion !== null).length}, repeat set: ${file.team.filter((t) => t.repeat_rate !== null).length})`);
const lko = file.stores.find((s) => s.store_id === "LKO-02");
if (lko) console.log(`LKO-02 conversion now: ${lko.conversion.now}% (baseline ${lko.conversion.baseline}%)`);
console.log("wrote data/generated/team.json");
