// Run: npx tsx --test lib/db/*.test.ts
import { test } from "node:test";
import assert from "node:assert/strict";
import { scorecardBody } from "./scorecard-body";

const generated = {
  _note: "Generated by npm run load",
  as_of: "2026-10-31",
  title: "Problems from the brief",
  store_rupees_at_stake: 760100,
  market_rupees_at_stake: 618300,
  biggest_issue_id: "2026-10-31:LKO-02:staff_absent_or_left",
  note: "A market note is not added to the store total.",
  rows: [
    { lever: "more_bills", brief_problem: "A whole city slowing down", type: "city_slowdown", kind: "market_note", status: "found", store_ids: ["KNP-01"], top_issue_id: "x", rupees_at_stake: 618300 },
    { lever: "more_bills", brief_problem: "Walk-ins steady", type: "conversion_drop_footfall_steady", kind: "store", status: "not_found", store_ids: [], top_issue_id: null, rupees_at_stake: null, reason: "No store had steady walk-ins and a conversion drop" },
  ],
};

test("scorecardBody passes rows through with kind and reason, plus both rupee totals", () => {
  const body = scorecardBody(generated);
  assert.equal(body.rows[0].kind, "market_note");
  assert.equal(body.rows[1].reason, "No store had steady walk-ins and a conversion drop");
  assert.equal(body.store_rupees_at_stake, 760100);
  assert.equal(body.market_rupees_at_stake, 618300);
  assert.equal(body.biggest_issue_id, "2026-10-31:LKO-02:staff_absent_or_left");
});

test("scorecardBody is honest about where the rows come from and drops the file note", () => {
  const body = scorecardBody(generated);
  assert.equal(body.source, "generated");
  assert.equal("_note" in body, false);
});
