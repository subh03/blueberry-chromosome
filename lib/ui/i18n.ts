const DICTS: Record<Lang, Dict> = { en, hi, bn };
export type Key = keyof Dict;

export function dict(lang: Lang): Dict {
  return DICTS[lang];
}

export function standingWord(lang: Lang, s: Standing) {
  const d = DICTS[lang];
  return s === "above" ? d.above : s === "below" ? d.below : s === "same" ? d.same : d.noData;
}
