export function langOf(value: unknown): Lang {
  return value === "hi" || value === "bn" ? value : "en";
}

/** Adds ?lang= to a link only when it isn't English, so English URLs stay as they were. */
export function withLang(href: string, lang: Lang) {
  if (lang === "en") return href;
  const [path, hash] = href.split("#");
  const joined = `${path}${path.includes("?") ? "&" : "?"}lang=${lang}`;
  return hash ? `${joined}#${hash}` : joined;
}

